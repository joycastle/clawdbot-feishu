async function writeValues(range: string, values: string[][]): Promise<void> {
  const fullRange = `${sheetId}!${range}`;
  
  const res = await (client as any).request({
    method: 'PUT',
    url: `/open-apis/sheets/v2/spreadsheets/${spreadsheetToken}/values`,
    data: {
      valueRange: {
        range: fullRange,
        values: values,
      },
    },
  });
  
  if (res.code !== 0) {
    throw new Error(`Failed to write values: ${res.msg}`);
  }
  console.log(`Successfully wrote ${values.length} rows to ${fullRange}`);
}

