async function resolveWikiToken(wikiToken: string): Promise<string> {
  const res = await (client as any).wiki.v2.space.getNode({
    params: { token: wikiToken },
  });
  if (res.code !== 0) {
    throw new Error(`Failed to resolve wiki token: ${res.msg}`);
  }
  const node = res.data?.node;
  if (!node) {
    throw new Error('Wiki node not found');
  }
  if (node.obj_type !== 'sheet') {
    throw new Error(`Wiki node is not a sheet (type: ${node.obj_type})`);
  }
  return node.obj_token;
}

async function writeValues(spreadsheetToken: string, sheetId: string, range: string, values: string[][]): Promise<void> {
  const fullRange = `${sheetId}!${range}`;
  
  const res = await (client as any).request({
    method: 'PUT',
    url: `/open-apis/sheets/v2/spreadsheets/${spreadsheetToken}/values`,
    data: {
      valueRange: {
        range: fullRange,
        values: values,
      },
    },
  });
  
  if (res.code !== 0) {
    throw new Error(`Failed to write values: ${res.msg}`);
  }
  console.log(`Successfully wrote ${values.length} rows to ${fullRange}`);
}

async function main() {
  console.log('Resolving wiki token...');
  const spreadsheetToken = await resolveWikiToken(wikiToken);
  console.log(`Spreadsheet token: ${spreadsheetToken}`);
  
  // 从第2行开始写入（第1行是表头）
  const startRow = 2;
  const endRow = startRow + testCases.length - 1;
  const range = `A${startRow}:E${endRow}`;
  
  console.log(`Writing ${testCases.length} test cases to ${range}...`);
  await writeValues(spreadsheetToken, sheetId, range, testCases);
  
  console.log('Done!');
}

